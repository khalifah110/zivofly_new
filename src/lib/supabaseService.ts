/**
 * Queries `public.integration_connections` for the active workspace and the 5 Google Workspace provider keys:
 * - `gmail`
 * - `google_drive`
 * - `google_docs`
 * - `google_sheets_service`
 * - `google_calendar`
 */
export async function getGoogleWorkspaceIntegrationConnections(params?: {
  workspaceId?: string | null;
  agentId?: string | null;
}): Promise<{
  workspaceId: string;
  connectionsByService: Record<
    GoogleWorkspaceServiceIdentifier,
    GoogleIntegrationConnectionRecord | null
  >;
}> {
  if (!supabase) {
    throw new Error('Supabase client is not configured.');
  }

  const { workspaceId } = await resolveActiveGoogleWorkspaceId(params);

  const { data, error } = await supabase
    .from('integration_connections')
    .select(
      'id, workspace_id, provider_key, display_name, status, external_account_id, external_account_name, scopes, connected_by, last_error, last_synced_at, metadata, created_at, updated_at'
    )
    .eq('workspace_id', workspaceId)
    .in('provider_key', [...GOOGLE_WORKSPACE_PROVIDER_KEYS])
    .order('updated_at', { ascending: false });

  if (error) {
    throw new Error(
      `Failed to load Google Workspace integration status: ${error.message}`
    );
  }

  const connectionsByService = createEmptyGoogleConnectionsMap();

  for (const row of data || []) {
    if (row.workspace_id !== workspaceId) continue;
    const mapped = mapIntegrationConnectionRow(row);
    if (!mapped) continue;
    // Keep the most recently updated record per provider_key
    if (!connectionsByService[mapped.provider_key]) {
      connectionsByService[mapped.provider_key] = mapped;
    }
  }

  return {
    workspaceId,
    connectionsByService,
  };
}

/**
 * Maps the actual `public.integration_connections` records onto `GoogleWorkspaceConfig`.
 * Ensures that only real database records determine connection status and account email,
 * while preserving any existing Google Sheet column configuration on `sheets`.
 */
export function syncGoogleWorkspaceConfigWithRecords(
  currentConfig: GoogleWorkspaceConfig | undefined,
  connectionsByService: Record<
    GoogleWorkspaceServiceIdentifier,
    GoogleIntegrationConnectionRecord | null
  >
): GoogleWorkspaceConfig {
  const buildAppEntry = (
    serviceKey: GoogleWorkspaceServiceIdentifier
  ): NonNullable<GoogleWorkspaceConfig['gmail']> => {
    const rec = connectionsByService[serviceKey];
    if (!rec) {
      return {
        enabled: false,
        status: 'disconnected',
        accountEmail: undefined,
        connectionId: undefined,
        lastError: null,
      };
    }

    return {
      enabled: rec.status === 'connected',
      status: rec.status,
      accountEmail: rec.account_email || undefined,
      connectionId: rec.id,
      lastError: rec.last_error,
      connectedAt: rec.created_at,
      lastSyncedAt: rec.last_synced_at || rec.updated_at,
    };
  };

  const sheetsRecord = connectionsByService.google_sheets_service;
  const existingSheets = currentConfig?.sheets || {
    enabled: false,
    columns: [],
    sheetName: 'Sheet1',
  };

  return {
    gmail: buildAppEntry('gmail'),
    drive: buildAppEntry('google_drive'),
    docs: buildAppEntry('google_docs'),
    sheets: {
      ...existingSheets,
      enabled: sheetsRecord?.status === 'connected',
      status: sheetsRecord ? sheetsRecord.status : 'disconnected',
      accountEmail: sheetsRecord?.account_email || undefined,
      connectionId: sheetsRecord?.id,
      lastError: sheetsRecord?.last_error || null,
      connectedAt: sheetsRecord?.created_at,
      lastSyncedAt:
        sheetsRecord?.last_synced_at ||
        sheetsRecord?.updated_at ||
        existingSheets.lastSyncedAt,
    },
    calendar: buildAppEntry('google_calendar'),
  };
}

export interface GoogleWorkspaceOAuthDiagnostic {
  errorName: string;
  errorMessage: string;
  errorContext: Record<string, any> | string | null;
  httpStatus: number | null;
  responseBody: Record<string, any> | string | null;
  functionEndpoint: string;
  selectedService: string;
  hasAuthenticatedSession: boolean;
  hasResolvedWorkspaceId: boolean;
  workspaceId: string | null;
  frontendOrigin: string;
  userFacingMessage: string;
}

function redactSensitiveFields(value: any): any {
  if (!value || typeof value !== 'object') return value;
  if (Array.isArray(value)) return value.map(redactSensitiveFields);

  const redacted: Record<string, any> = {};
  const sensitivePattern =
    /token|secret|password|key|authorization|credential|cookie/i;

  for (const [k, v] of Object.entries(value)) {
    if (sensitivePattern.test(k)) {
      redacted[k] = '[REDACTED]';
    } else if (v && typeof v === 'object') {
      redacted[k] = redactSensitiveFields(v);
    } else {
      redacted[k] = v;
    }
  }
  return redacted;
}

async function buildGoogleWorkspaceEdgeDiagnostic(params: {
  error: any;
  response?: Response;
  data?: any;
  service: string;
  hasAuthenticatedSession: boolean;
  workspaceId: string | null;
}): Promise<GoogleWorkspaceOAuthDiagnostic> {
  const {
    error,
    response,
    data,
    service,
    hasAuthenticatedSession,
    workspaceId,
  } = params;

  const functionEndpoint = `${SUPABASE_URL}/functions/v1/google_workspace`;
  const frontendOrigin =
    typeof window !== 'undefined' && window.location?.origin
      ? window.location.origin
      : 'unknown';
  const hasResolvedWorkspaceId = isValidUuid(workspaceId);
  const serviceLabel = isGoogleWorkspaceServiceIdentifier(service)
    ? GOOGLE_WORKSPACE_SERVICE_LABELS[service]
    : service || 'Google Workspace';

  const errorName =
    typeof error?.name === 'string' && error.name.trim()
      ? error.name.trim()
      : 'EdgeFunctionError';
  const rawErrorMessage =
    typeof error?.message === 'string' && error.message.trim()
      ? error.message.trim()
      : 'Unknown error calling google_workspace Edge Function.';

  const ctx = error?.context;
  let httpStatus: number | null =
    typeof response?.status === 'number'
      ? response.status
      : typeof ctx?.status === 'number'
      ? ctx.status
      : typeof error?.status === 'number'
      ? error.status
      : null;

  let errorContextSummary: Record<string, any> | string | null = null;
  let responseBody: Record<string, any> | string | null = null;

  if (ctx) {
    if (typeof ctx.text === 'function') {
      errorContextSummary = {
        type: 'Response',
        status: ctx.status ?? httpStatus,
        statusText: ctx.statusText || '',
        ok: Boolean(ctx.ok),
        url: ctx.url || functionEndpoint,
      };
      try {
        const rawText =
          typeof ctx.clone === 'function'
            ? await ctx.clone().text()
            : await ctx.text();
        if (rawText && rawText.trim()) {
          try {
            responseBody = redactSensitiveFields(JSON.parse(rawText));
          } catch {
            responseBody = rawText.trim();
          }
        }
      } catch {
        // Response stream already consumed
      }
    } else if (ctx instanceof Error || typeof ctx?.message === 'string') {
      errorContextSummary = {
        name: ctx.name || 'Error',
        message: ctx.message,
      };
    } else if (typeof ctx === 'object') {
      errorContextSummary = redactSensitiveFields(ctx);
    } else {
      errorContextSummary = String(ctx);
    }
  }

  if (!responseBody && data !== undefined && data !== null) {
    responseBody =
      typeof data === 'object' ? redactSensitiveFields(data) : String(data);
  }

  // Extract the clearest server error detail if present in responseBody
  let serverDetail = '';
  if (responseBody && typeof responseBody === 'object') {
    const rb = responseBody as Record<string, any>;
    serverDetail =
      rb.error || rb.message || rb.details || rb.msg || rb.reason || '';
  } else if (typeof responseBody === 'string') {
    serverDetail = responseBody;
  }

  let userFacingMessage = '';
  const isNetworkOrCorsFailure =
    errorName === 'FunctionsFetchError' ||
    rawErrorMessage.includes('Failed to send a request to the Edge Function') ||
    rawErrorMessage.includes('Failed to fetch');

  if (!hasAuthenticatedSession) {
    userFacingMessage = `Cannot connect ${serviceLabel}: No active authenticated session found. Please sign in and try again.`;
  } else if (!hasResolvedWorkspaceId) {
    userFacingMessage = `Cannot connect ${serviceLabel}: Could not resolve an active workspace ID for your account.`;
  } else if (isNetworkOrCorsFailure) {
    const underlyingCause =
      typeof (errorContextSummary as any)?.message === 'string'
        ? (errorContextSummary as any).message
        : rawErrorMessage;
    const isNonProdOrigin =
      frontendOrigin !== 'https://zivofly.pages.dev' &&
      frontendOrigin !== 'unknown';

    if (isNonProdOrigin) {
      userFacingMessage = `Failed to reach google_workspace for ${serviceLabel} (${underlyingCause}): Current origin "${frontendOrigin}" does not match the Edge Function's allowed CORS origin ("https://zivofly.pages.dev").`;
    } else {
      userFacingMessage = `Failed to reach google_workspace for ${serviceLabel} at ${functionEndpoint} (${underlyingCause}). Check browser network/CORS preflight headers (authorization, apikey, content-type, x-client-info).`;
    }
  } else if (httpStatus && serverDetail) {
    userFacingMessage = `${serviceLabel} authorization failed (HTTP ${httpStatus}): ${serverDetail}`;
  } else if (serverDetail) {
    userFacingMessage = `${serviceLabel} authorization failed: ${serverDetail}`;
  } else if (httpStatus) {
    userFacingMessage = `${serviceLabel} authorization failed with HTTP ${httpStatus}: ${rawErrorMessage}`;
  } else {
    userFacingMessage = `${serviceLabel} authorization failed: ${rawErrorMessage}`;
  }

  const diagnostic: GoogleWorkspaceOAuthDiagnostic = {
    errorName,
    errorMessage: rawErrorMessage,
    errorContext: errorContextSummary,
    httpStatus,
    responseBody,
    functionEndpoint,
    selectedService: service,
    hasAuthenticatedSession,
    hasResolvedWorkspaceId,
    workspaceId: hasResolvedWorkspaceId ? workspaceId : null,
    frontendOrigin,
    userFacingMessage,
  };

  console.error(
    '[Google Workspace OAuth] Edge Function request diagnostic:',
    diagnostic
  );

  return diagnostic;
}

/**
 * Initiates the Google Workspace OAuth flow for one of the 5 services by invoking
 * the deployed `google_workspace` Supabase Edge Function:
 * `{ action: "start", workspace_id, service }`
 */
export async function startGoogleWorkspaceOAuth(params: {
  service: GoogleWorkspaceServiceIdentifier;
  workspaceId?: string | null;
  agentId?: string | null;
}): Promise<{
  authorizationUrl: string;
  workspaceId: string;
  service: GoogleWorkspaceServiceIdentifier;
}> {
  const functionEndpoint = `${SUPABASE_URL}/functions/v1/google_workspace`;

  if (!supabase || !SUPABASE_URL || !SUPABASE_ANON_KEY) {
    const configErr = new Error(
      'Supabase client is not configured (missing project URL or anon key).'
    );
    await buildGoogleWorkspaceEdgeDiagnostic({
      error: configErr,
      service: params.service,
      hasAuthenticatedSession: false,
      workspaceId: params.workspaceId || null,
    });
    throw configErr;
  }

  if (!isGoogleWorkspaceServiceIdentifier(params.service)) {
    const invalidServiceErr = new Error(
      `Invalid Google Workspace service identifier: "${params.service}".`
    );
    await buildGoogleWorkspaceEdgeDiagnostic({
      error: invalidServiceErr,
      service: String(params.service || ''),
      hasAuthenticatedSession: false,
      workspaceId: params.workspaceId || null,
    });
    throw invalidServiceErr;
  }

  const service = params.service;
  if (inFlightGoogleOAuthServices.has(service)) {
    throw new Error(
      `An authorization request for ${GOOGLE_WORKSPACE_SERVICE_LABELS[service]} is already in progress.`
    );
  }

  inFlightGoogleOAuthServices.add(service);

  let hasAuthenticatedSession = false;
  let resolvedWorkspaceId: string | null = null;

  try {
    // 1. Verify authenticated Supabase session & resolve active workspace ID
    let accessToken = '';
    try {
      const resolved = await resolveActiveGoogleWorkspaceId({
        workspaceId: params.workspaceId,
        agentId: params.agentId,
      });
      accessToken = resolved.accessToken;
      hasAuthenticatedSession = Boolean(accessToken);
      resolvedWorkspaceId = resolved.workspaceId;
    } catch (preCheckErr: any) {
      const { data: sessionCheck } = await supabase.auth
        .getSession()
        .catch(() => ({ data: { session: null } }));
      hasAuthenticatedSession = Boolean(sessionCheck?.session?.access_token);

      const diag = await buildGoogleWorkspaceEdgeDiagnostic({
        error: preCheckErr,
        service,
        hasAuthenticatedSession,
        workspaceId: resolvedWorkspaceId || params.workspaceId || null,
      });
      throw new Error(diag.userFacingMessage);
    }

    if (!isValidUuid(resolvedWorkspaceId)) {
      const missingWsErr = new Error(
        'A valid active workspace ID is required to connect Google Workspace.'
      );
      const diag = await buildGoogleWorkspaceEdgeDiagnostic({
        error: missingWsErr,
        service,
        hasAuthenticatedSession,
        workspaceId: resolvedWorkspaceId,
      });
      throw new Error(diag.userFacingMessage);
    }

    const requestBody = {
      action: 'start' as const,
      workspace_id: resolvedWorkspaceId,
      service,
    };

    console.info('[Google Workspace OAuth] Invoking google_workspace:', {
      functionEndpoint,
      selectedService: service,
      workspaceId: resolvedWorkspaceId,
      hasAuthenticatedSession,
      hasResolvedWorkspaceId: true,
      frontendOrigin:
        typeof window !== 'undefined' ? window.location.origin : 'unknown',
    });

    // 2. Invoke the deployed `google_workspace` Edge Function.
    // The Supabase client's `functionsFetch` automatically attaches `apikey` and `Authorization: Bearer <session.access_token>`,
    // and `supabaseCustomFetch` in `src/lib/supabaseClient.ts` strips `x-client-info` so browser CORS preflight succeeds.
    const { data, error, response } = await supabase.functions.invoke(
      'google_workspace',
      {
        body: requestBody,
      }
    );

    if (error) {
      const diag = await buildGoogleWorkspaceEdgeDiagnostic({
        error,
        response,
        data,
        service,
        hasAuthenticatedSession,
        workspaceId: resolvedWorkspaceId,
      });
      throw new Error(diag.userFacingMessage);
    }

    if (data?.error) {
      const payloadErr = new Error(
        typeof data.error === 'string'
          ? data.error
          : JSON.stringify(data.error)
      );
      const diag = await buildGoogleWorkspaceEdgeDiagnostic({
        error: payloadErr,
        response,
        data,
        service,
        hasAuthenticatedSession,
        workspaceId: resolvedWorkspaceId,
      });
      throw new Error(diag.userFacingMessage);
    }

    const authorizationUrl =
      typeof data?.authorization_url === 'string'
        ? data.authorization_url.trim()
        : '';

    if (
      !authorizationUrl ||
      (!authorizationUrl.startsWith('https://') &&
        !authorizationUrl.startsWith('http://'))
    ) {
      const missingUrlErr = new Error(
        'The google_workspace Edge Function did not return a valid authorization_url.'
      );
      const diag = await buildGoogleWorkspaceEdgeDiagnostic({
        error: missingUrlErr,
        response,
        data,
        service,
        hasAuthenticatedSession,
        workspaceId: resolvedWorkspaceId,
      });
      throw new Error(diag.userFacingMessage);
    }

    // 3. Save return navigation context so the callback restores the exact Agent Tools view
    try {
      sessionStorage.setItem(
        GOOGLE_OAUTH_RETURN_STORAGE_KEY,
        JSON.stringify({
          path: window.location.pathname,
          tab: 'tools',
          workspaceId: resolvedWorkspaceId,
          agentId: params.agentId || null,
          service,
          createdAt: Date.now(),
        })
      );
    } catch {
      // Ignore storage quota errors
    }

    return {
      authorizationUrl,
      workspaceId: resolvedWorkspaceId,
      service,
    };
  } finally {
    inFlightGoogleOAuthServices.delete(service);
  }
}

export interface GoogleOAuthCallbackResult {
  handled: boolean;
  outcome?: 'success' | 'error';
  service?: GoogleWorkspaceServiceIdentifier;
  serviceLabel?: string;
  email?: string | null;
  connectionId?: string | null;
  message?: string;
  workspaceId?: string;
  connectionsByService?: Record<
    GoogleWorkspaceServiceIdentifier,
    GoogleIntegrationConnectionRecord | null
  >;
}

/**
 * Strips Google OAuth callback query parameters (`google_oauth`, `service`, `email`, `connection_id`, `reason`)
 * from the browser URL so refreshing the page does not repeat callback handling or notifications.
 */
export function clearGoogleOAuthUrlParams(): void {
  const url = new URL(window.location.href);
  const keysToRemove = [
    'google_oauth',
    'service',
    'email',
    'connection_id',
    'reason',
  ];
  let modified = false;
  for (const key of keysToRemove) {
    if (url.searchParams.has(key)) {
      url.searchParams.delete(key);
      modified = true;
    }
  }
  if (modified) {
    const nextSearch = url.searchParams.toString();
    const cleanUrl = `${url.pathname}${nextSearch ? `?${nextSearch}` : ''}${url.hash || ''}`;
    window.history.replaceState({}, '', cleanUrl);
  }
}

/**
 * Inspects the current browser URL for Google OAuth callback query parameters:
 * - Success: `google_oauth=success`, `service`, `email`, `connection_id`
 * - Failure: `google_oauth=error`, `reason`
 *
 * IMPORTANT: Never trusts the frontend redirect parameters alone.
 * Queries `public.integration_connections` in Supabase to confirm the saved connection
 * and its actual status (`status === 'connected'`).
 */
export async function processGoogleWorkspaceOAuthCallbackFromUrl(params?: {
  workspaceId?: string | null;
  agentId?: string | null;
}): Promise<GoogleOAuthCallbackResult> {
  const currentSearch = window.location.search || '';
  if (!currentSearch) {
    return { handled: false };
  }

  const searchParams = new URLSearchParams(currentSearch);
  const oauthStatus = searchParams.get('google_oauth')?.trim().toLowerCase();

  if (oauthStatus !== 'success' && oauthStatus !== 'error') {
    return { handled: false };
  }

  if (lastProcessedGoogleOAuthQuery === currentSearch) {
    clearGoogleOAuthUrlParams();
    return { handled: false };
  }
  lastProcessedGoogleOAuthQuery = currentSearch;

  const rawService = searchParams.get('service')?.trim() || '';
  const rawEmail = searchParams.get('email')?.trim() || null;
  const rawConnectionId = searchParams.get('connection_id')?.trim() || null;
  const rawReason = searchParams.get('reason')?.trim() || '';

  // Clean URL parameters immediately so page refresh will not re-trigger the callback toast
  clearGoogleOAuthUrlParams();
  try {
    sessionStorage.removeItem(GOOGLE_OAUTH_RETURN_STORAGE_KEY);
  } catch {
    // ignore
  }

  const validService = isGoogleWorkspaceServiceIdentifier(rawService)
    ? rawService
    : undefined;
  const serviceLabel = validService
    ? GOOGLE_WORKSPACE_SERVICE_LABELS[validService]
    : 'Google Workspace';

  if (oauthStatus === 'error') {
    const formattedReason = rawReason
      ? decodeURIComponent(rawReason).replace(/_/g, ' ')
      : 'Authorization was cancelled or could not be completed.';

    let connectionsByService:
      | Record<
          GoogleWorkspaceServiceIdentifier,
          GoogleIntegrationConnectionRecord | null
        >
      | undefined;
    let workspaceId: string | undefined;

    try {
      const refreshed = await getGoogleWorkspaceIntegrationConnections(params);
      workspaceId = refreshed.workspaceId;
      connectionsByService = refreshed.connectionsByService;
    } catch {
      // Keep existing state if user is not authenticated
    }

    return {
      handled: true,
      outcome: 'error',
      service: validService,
      serviceLabel,
      message: `Failed to connect ${serviceLabel}: ${formattedReason}`,
      workspaceId,
      connectionsByService,
    };
  }

  // Handle `google_oauth=success`
  if (!validService) {
    return {
      handled: true,
      outcome: 'error',
      message:
        'Google OAuth callback returned an unrecognized service identifier.',
    };
  }

  if (rawConnectionId && !isValidUuid(rawConnectionId)) {
    return {
      handled: true,
      outcome: 'error',
      service: validService,
      serviceLabel,
      message:
        'Google OAuth callback returned an invalid connection_id parameter.',
    };
  }

  // Query actual `public.integration_connections` rows from Supabase to confirm the saved connection
  const { workspaceId, connectionsByService } =
    await getGoogleWorkspaceIntegrationConnections(params);

  let verifiedRecord = connectionsByService[validService];

  // If connection_id was specified, verify the exact row in `public.integration_connections`
  if (rawConnectionId && supabase) {
    const { data: exactRow } = await supabase
      .from('integration_connections')
      .select(
        'id, workspace_id, provider_key, display_name, status, external_account_id, external_account_name, scopes, connected_by, last_error, last_synced_at, metadata, created_at, updated_at'
      )
      .eq('id', rawConnectionId)
      .eq('workspace_id', workspaceId)
      .eq('provider_key', validService)
      .maybeSingle();

    const mappedExact = mapIntegrationConnectionRow(exactRow);
    if (mappedExact) {
      verifiedRecord = mappedExact;
      connectionsByService[validService] = mappedExact;
    }
  }

  if (!verifiedRecord || verifiedRecord.status !== 'connected') {
    const statusDesc = verifiedRecord
      ? `status is "${verifiedRecord.status}"${
          verifiedRecord.last_error ? ` (${verifiedRecord.last_error})` : ''
        }`
      : 'no saved connection record was found in Supabase';

    return {
      handled: true,
      outcome: 'error',
      service: validService,
      serviceLabel,
      workspaceId,
      connectionsByService,
      message: `Could not verify ${serviceLabel} connection in Supabase (${statusDesc}).`,
    };
  }

  const confirmedEmail = verifiedRecord.account_email || rawEmail || null;
  if (confirmedEmail && !verifiedRecord.account_email) {
    verifiedRecord.account_email = confirmedEmail;
  }

  return {
    handled: true,
    outcome: 'success',
    service: validService,
    serviceLabel,
    email: confirmedEmail,
    connectionId: verifiedRecord.id,
    workspaceId,
    connectionsByService,
    message: confirmedEmail
      ? `Connected ${serviceLabel} (${confirmedEmail}) successfully!`
      : `Connected ${serviceLabel} successfully!`,
  };
}
